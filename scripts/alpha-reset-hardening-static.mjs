import { readFileSync } from "node:fs";
import { strict as assert } from "node:assert";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const tool = readFileSync(resolve(root, "scripts/alpha-reset.mjs"), "utf8");
const helper = readFileSync(resolve(root, "ops/ocg-alpha-reset"), "utf8");
for (const marker of ["realpathSync", "lstatSync", "symlink path component rejected", "PRODUCTION_BASE_ROOT", "PRODUCTION_BACKUP_ROOT", "PRODUCTION_RUNTIME_ROOT", "PRODUCTION_STATE_ROOT", "RUNTIME_ARCHIVED", "RUNTIME_REINITIALIZED", "DB_COMMITTED", "RECOVERY_REQUIRED", "runtimeArchive", "backup-sha256", "fsyncSync", "--resume"]) assert.match(tool, new RegExp(marker.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
assert.doesNotMatch(tool, /eval\s*\(/);
assert.match(tool, /rootPath:TEST_MODE \? null : PRODUCTION_BASE_ROOT/);
assert.match(tool, /requestedRuntime && resolve\(requestedRuntime\) !== resolve\(PRODUCTION_RUNTIME_ROOT\)/);
assert.match(tool, /phase:"RUNTIME_ARCHIVED"/);
assert.match(tool, /phase:"RUNTIME_REINITIALIZED"/);
assert.match(tool, /phase:"DB_COMMITTED"/);
assert.match(tool, /phase:"COMPLETED"/);
assert.match(tool, /phase:"RECOVERY_REQUIRED"/);
assert.match(tool, /restoreRuntimeStores\(current\.archive\)/);
assert.match(tool, /rootPath:runtimeDir, type:"directory", label:"runtime archive"/);
assert.match(helper, /readonly RUNTIME_DIR="\$\{BASE_DIR\}\/runtime"/);
assert.match(helper, /readonly NODE="\/usr\/bin\/node"/);
assert.match(helper, /--apply/);
assert.match(helper, /--dry-run/);
assert.doesNotMatch(helper, /sudo|systemctl|bash -c|eval\s*\(/);
assert.match(helper, /exec "\$\{NODE\}"/);
assert.match(helper, /EUID.*-eq 0/);
assert.match(helper, /current.*symlink|CURRENT_LINK/);
assert.match(helper, /unset OCG_ALPHA_RESET_TEST/);
console.log("ALPHA_RESET_HARDENING_STATIC_OK");
